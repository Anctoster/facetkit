#!/usr/bin/env node
// Builds plugin/ — the Claude Code plugin as the plugin directory accepts it from an unverified
// publisher: Markdown and JSON only (agents, commands, skills), no bin/ and no code. The `facet`
// command itself comes from npm (`npm i -g facetkit` or `npx --yes facetkit`). In the plugin every
// launcher is pinned to this version (`facetkit@x.y.z`): the directory blocks an unpinned `npx`.
//
//   node scripts/build-plugin.mjs           write plugin/
//   node scripts/build-plugin.mjs --check   exit 1 when plugin/ differs from what would be written
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'plugin');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf-8'));

/** Fields of plugin.json that Claude Code reads; nothing else goes in. */
const PLUGIN_FIELDS = ['name', 'version', 'description', 'author', 'homepage', 'repository', 'license', 'keywords'];

const manifest = {
    name: pkg.name,
    version: pkg.version,
    description: pkg.description,
    author: { name: pkg.author },
    homepage: pkg.homepage,
    repository: pkg.repository.url.replace(/^git\+/, '').replace(/\.git$/, ''),
    license: pkg.license,
    keywords: pkg.keywords,
};

const readme = `# facetkit — Claude Code plugin

Evidence-first engineering for teams of AI agents. This folder is the plugin: the nine agents, the
commands \`/facet-item\`, \`/facet-session\` and \`/facet-retro\`, and the fourteen skills cut into facets.

The agents and commands call the \`facet\` command. It is not part of the plugin; install it once:

\`\`\`bash
npm i -g facetkit@${pkg.version}        # or let the agents run \`npx --yes facetkit@${pkg.version} …\`
facet init --minimal     # in your project
\`\`\`

## What it runs and touches

- **Runs:** the \`facet\` command from the npm package \`facetkit@${pkg.version}\` (pinned; no dependencies), and the
  commands of your own project that you list as checks in \`facet.json\` (tests, build, lint).
- **Reads and writes:** files in your project only — the journal (\`docs/journal\` or what \`facet.json\` names),
  \`.work/\` for the handoffs of the item in progress, \`.facet/\`, and \`facet-board.html\`. \`facet cost import\`
  reads a Claude Code session transcript only when you pass its path.
- **Sends:** nothing. facetkit has no server, no telemetry and no network calls; the only download is npm
  fetching the package when \`npx\` runs it.

Documentation, the tools and the source: ${pkg.homepage.replace(/#readme$/, '')}

This folder is generated by \`node scripts/build-plugin.mjs\`; edit \`agents/\`, \`commands/\` and \`skills/\`
in the repository root instead.
`;

/** `npx --yes facetkit` → `npx --yes facetkit@<version>`: the plugin runs exactly the release it was built with. */
const pin = (text) => text.replaceAll(/npx --yes facetkit(?!@)/g, `npx --yes facetkit@${pkg.version}`);

/** Every file of the plugin: relative path → content. */
function planned() {
    const files = new Map();
    const walk = (dir) => {
        for (const entry of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
            const rel = path.join(dir, entry.name);
            if (entry.isDirectory()) walk(rel);
            else if (entry.name.endsWith('.md')) files.set(rel, Buffer.from(pin(fs.readFileSync(path.join(ROOT, rel), 'utf-8'))));
        }
    };
    for (const dir of ['agents', 'commands', 'skills']) walk(dir);
    files.set('LICENSE', fs.readFileSync(path.join(ROOT, 'LICENSE')));
    files.set('README.md', Buffer.from(readme));
    files.set(path.join('.claude-plugin', 'plugin.json'), Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`));
    return files;
}

/** Files now in plugin/ (relative paths). */
function existing(dir = '') {
    const abs = path.join(OUT, dir);
    if (!fs.existsSync(abs)) return [];
    return fs.readdirSync(abs, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? existing(path.join(dir, e.name)) : [path.join(dir, e.name)]));
}

const files = planned();
if (process.argv.includes('--check')) {
    const have = existing();
    const stale = [...files].filter(([rel, content]) => !fs.existsSync(path.join(OUT, rel)) || !fs.readFileSync(path.join(OUT, rel)).equals(content)).map(([rel]) => rel);
    const extra = have.filter((rel) => !files.has(rel));
    if (stale.length || extra.length) {
        console.log(`plugin/ is out of date — run: node scripts/build-plugin.mjs\n${[...stale.map((f) => `  changed ${f}`), ...extra.map((f) => `  extra   ${f}`)].join('\n')}`);
        process.exit(1);
    }
    console.log(`plugin/ is up to date (${files.size} files)`);
} else {
    fs.rmSync(OUT, { recursive: true, force: true });
    for (const [rel, content] of files) {
        fs.mkdirSync(path.dirname(path.join(OUT, rel)), { recursive: true });
        fs.writeFileSync(path.join(OUT, rel), content);
    }
    console.log(`plugin/: ${files.size} files written`);
}
